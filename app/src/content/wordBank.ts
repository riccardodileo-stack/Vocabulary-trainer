// Built-in list of words suggested as "words of the day".
// Each row is one concept in every supported language, so the same list works
// for any language pair (studied word in one column, translation in another).
//
// Row format: [level, english, italian, spanish, french, german, categories?]
// Levels go from A1 to C2 (CEFR). Categories are the topic ids of domain/topics.ts: they let
// the user ask for words of the day of one or more categories (rows without them are general
// words, suggested only when no category is chosen).
// - Alternatives are separated by " / ": the first one is the word suggested
//   when that language is studied, all of them are accepted as translations.
// - English verbs start with "to", German nouns are capitalized, no articles.
//
// To add words, append rows here, in the section of their first category (the id is the first
// English alternative, so it must be unique). Each category should keep at least 10 words for
// each group of levels (A, B, C): a test checks it. When suggestions come from a server, this file stays
// as the offline fallback: see services/dailyWords.ts.

