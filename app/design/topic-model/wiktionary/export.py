# Writes app/src/content/senseTopics.ts from words.json and pairs.json (made by build.py).
# Kept in the app:
# - words: translation -> topics, from every Wiktionary table the word is in ("ictus" -> health);
# - pairs: (word, translation) -> topics where the pair says more than its two words alone
#   ("court" = "campo" -> sport, while "campo" alone has no clear topic).
# Only words of the 50,000 most common of each language, to keep the app small.
import json, collections, sys, datetime
exec(open('build.py').read().split("rows = load()")[0])  # fold, common, LANGS, ORDER

OUT = sys.argv[1] if len(sys.argv) > 1 else 'senseTopics.ts'
mask = lambda topics: format(sum(1 << ORDER.index(t) for t in topics), 'x')

words = json.load(open('words.json'))
pairs = json.load(open('pairs.json'))
W = {(l, w): t for l, w, t in words}

g = collections.defaultdict(lambda: collections.defaultdict(list))
for l, w, t in words:
    g[l][mask(t)].append(w)
gp = collections.defaultdict(lambda: collections.defaultdict(list))
kept = 0
for a, b, x, y, t in pairs:
    if not (common(x, a) and common(y, b)):
        continue
    if W.get((b, y)) == t and W.get((a, x)) == t:
        continue
    gp[f'{a}-{b}'][mask(t)].append(f'{x}={y}')
    kept += 1

def pack(groups):
    return {k: ';'.join(f'{m}:' + ','.join(sorted(v)) for m, v in sorted(d.items())) for k, d in sorted(groups.items())}

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// GENERATED by design/topic-model/wiktionary/export.py — do not edit by hand.\n')
    f.write('// Topics of meanings taken from Wiktionary (kaikki.org extract, CC BY-SA): see\n')
    f.write('// design/topic-model/wiktionary/README.md and src/domain/topicClassifier.ts.\n\n')
    f.write('export const SENSE_TOPICS = {\n')
    f.write(f'  /** Date of the Wiktionary extract. */\n  source: {json.dumps("kaikki.org " + datetime.date.today().isoformat())},\n')
    f.write('  /** Per language, "mask:word,word;…": translation -> topics (bits in TOPIC_IDS order). */\n')
    f.write(f'  words: {json.dumps(pack(g), ensure_ascii=False)},\n')
    f.write('  /** Per language pair "a-b" (a < b), "mask:wordA=wordB,…": topics of that pair of words. */\n')
    f.write(f'  pairs: {json.dumps(pack(gp), ensure_ascii=False)},\n')
    f.write('};\n')
print('words', len(words), 'pairs kept', kept, file=sys.stderr)
