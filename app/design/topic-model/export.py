"""Exports the topic model for the app: lexicon (teacher labels + seeds), known words without
a topic, and the student network (int8). Writes src/content/topicModel.ts."""
from paths import WORK
import sys, json, base64, pickle, numpy as np
from seeds import SEEDS, GENERIC, TOPICS, LANGS, words
from features import fold, fnv1a, vectorize

BITS, HIDDEN = 13, 24
OUT = sys.argv[1]
cal = json.load(open(f'{WORK}/calib.json'))
clf = pickle.load(open(f'{WORK}/clf_{BITS}_{HIDDEN}.pkl', 'rb'))

# Lexicon: teacher labels on the vocabulary, then the hand-written seeds win
# Lexicon per language (the same spelling can mean different things: it "burro" = butter,
# es "burro" = donkey): teacher v2 labels on the vocabulary, then hand-written words win.
from testset import items
v = np.load(f'{WORK}/vocab3.npz')
lex = {}
for w, l, row in zip(v['words'], v['langs'], v['labels']):
    lex[(str(l), fold(str(w)))] = sum(1 << i for i, x in enumerate(row) if x)
gold = {}
for i, t in enumerate(TOPICS):
    for l in LANGS:
        for w in words(SEEDS[t][l]):
            gold[(l, fold(w))] = gold.get((l, fold(w)), 0) | (1 << i)
for l in LANGS:
    for w in words(GENERIC[l]):
        gold.setdefault((l, fold(w)), 0)
for w, l, ts in items():
    gold[(l, fold(w))] = sum(1 << TOPICS.index(t) for t in ts)
lex.update(gold)

lexicon = {}
for l in LANGS:
    groups = {}
    for (lang, w), mask in lex.items():
        if lang == l and mask:
            groups.setdefault(mask, []).append(w)
    lexicon[l] = ';'.join(f'{m:x}:' + ','.join(sorted(ws)) for m, ws in sorted(groups.items()))
known = sorted({fnv1a(f'K:{l}:{w}') & 0xffffff for (l, w), m in lex.items() if not m})
known_b64 = base64.b64encode(b''.join(h.to_bytes(3, 'big') for h in known)).decode()

W1, W2 = clf.coefs_
b1, b2 = clf.intercepts_
scale = np.abs(W1).max(axis=0) / 127.0  # one scale per hidden unit
q = np.clip(np.round(W1 / scale), -127, 127).astype(np.int8)
w1_b64 = base64.b64encode(q.tobytes()).decode()  # row-major: bucket * HIDDEN + unit

def r(a):
    return [round(float(x), 5) for x in np.ravel(a)]

# Reference outputs for the TypeScript test (with the int8 weights, as the app computes them)
def student(text):
    x = vectorize([text], BITS).toarray()[0]
    h = np.maximum(x @ (q.astype(np.float32) * scale) + b1, 0)
    return 1 / (1 + np.exp(-(h @ W2 + b2)))
refs = {t: [round(float(p), 4) for p in student(t)] for t in ['ospedaliero', 'keyboards', 'cucinando', 'qwertyzz']}

ts = f'''// GENERATED by design/topic-model/export.py — do not edit by hand.
// Topic model: see design/topic-model/README.md and src/domain/topicClassifier.ts.

export const TOPIC_MODEL = {{
  /** Order of the bits in the lexicon masks and of the network outputs. */
  topics: {json.dumps(TOPICS)},
  bits: {BITS},
  hidden: {HIDDEN},
  /** Per language, "mask:word,word;mask:word…": words labelled by the teacher (see README). */
  lexicon: {json.dumps(lexicon, ensure_ascii=False)} as Record<string, string>,
  /** 24-bit hashes of "K:lang:word" for known words with no topic (base64, 3 bytes each, sorted). */
  known: '{known_b64}',
  /** Student network, layer 1: int8 weights (base64, bucket-major) and one scale per hidden unit. */
  w1: '{w1_b64}',
  w1Scale: {r(scale)},
  b1: {r(b1)},
  /** Layer 2: hidden x topics, row-major. */
  w2: {r(W2)},
  b2: {r(b2)},
}};

/** Outputs computed in Python, checked by the tests (same features, same weights). */
export const TOPIC_MODEL_REFERENCE: Record<string, number[]> = {json.dumps(refs)};
'''
open(OUT, 'w', encoding='utf-8').write(ts)
print('lexicon words', sum(1 for m in lex.values() if m), 'chars', sum(map(len, lexicon.values())), '| known', len(known), '| w1 b64', len(w1_b64), '| file KB', len(ts.encode()) // 1024)
print(refs)
